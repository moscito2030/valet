import test from 'node:test';
import assert from 'node:assert/strict';
import { createEvent } from '../lib/domain/event-factory';
import { duplicateStage } from '../lib/domain/duplicate-stage';
import { project } from '../lib/scoring';
for (const kind of ['pairs','teams'] as const) test(`${kind} stage copy keeps the setup and drops scores unless requested`, () => {
  const source = createEvent({kind,name:'Source',names:['A','B','C','D'],date:'2026-10-19',venue:'Hall',rounds:1,boardsPerRound:2});
  const a=source.assignments[0];
  source.results[`${a.id}:1`]={assignmentId:a.id,board:1,level:1,strain:'NT',doubled:1,declarer:'N',tricks:7,lead:'',nsScore:90,updatedAt:'now'};
  source.club={enabled:true,mode:'table',tokens:{device:'fixture-only'},confirmations:{'1:p1':{at:'now',forced:false}},finalized:[1],publishedAssignments:[a.id]};
  source.currentRound = 1;
  source.roundPhase = 'break';
  source.status = 'review';
  source.penalties={[source.participants[0].id]:1};
  const original=structuredClone(source),copy=duplicateStage(source,'Copy');
  assert.notEqual(copy.id,source.id);
  assert.equal(copy.parentEventId,source.id);
  assert.equal(copy.stageName,'Copy');
  assert.deepEqual(copy.results,{});
  assert.deepEqual(copy.penalties,{});
  assert.equal(copy.status,'live');
  assert.equal(copy.currentRound,undefined);
  assert.deepEqual(copy.club?.finalized,[]);
  assert.equal(copy.club?.publishedAssignments,undefined);
  assert.deepEqual(copy.club?.tokens,{});
  assert.deepEqual(copy.boards,source.boards);
  const full=duplicateStage(source,'Full',true);
  assert.equal(full.results[`${a.id}:1`].nsScore,90);
  assert.deepEqual(full.club?.finalized,[1]);
  assert.deepEqual(project(full),project(source));
  assert.equal(copy.audit.length,1);
  assert.equal(copy.revision,1);
  full.results[`${a.id}:1`].nsScore=999;
  copy.participants[0].name='Changed';
  assert.deepEqual(source,original);
  source.parentEventId='parent';
  assert.equal(duplicateStage(source,'Sibling').parentEventId,'parent');
});
